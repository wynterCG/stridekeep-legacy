-- Stridekeep · 0012_feed_events (Phase-4 Mosaic Edition · Step 5 / S5.A)
--
-- Replaces the Phase-3 deposits table with a 5-event-kind feed:
--   tile_placed   — real-player canvas placement (place_tile RPC writes)
--   case_opened   — tier + rolled colorId (real or atmospheric)
--   crafted       — output color (real or atmospheric)
--   sold          — colorId + qty (real or atmospheric)
--   shop_bought   — colorId + qty (real or atmospheric)
--
-- Phase-3 deposits table is dropped here. There are no foreign keys
-- pointing into it, so the drop is clean. Note: the React Native client's
-- useTownFeed hook still polls public.deposits — once this migration is
-- applied, that hook will start logging "relation does not exist" errors
-- on every 1-second tick until Step 6 swaps it to feed_events. Either
-- expect the spam window for the Step-5 → Step-6 gap, or hold this
-- migration until Step 6 is also ready to go.
--
-- Renumbered from spec 0014 to 0012 because feed_events must exist
-- before the place_tile RPC (spec 0012, our 0013) inserts into it. See
-- 0009's header for the full ordering rationale.

-- ─── Drop legacy deposits ────────────────────────────────────────────────
-- The dependency-aware drop: deposit_for_town RPC referenced public.deposits,
-- so we drop both. The replacement RPC (place_tile) writes to feed_events.
drop function if exists public.deposit_for_town(bigint);
drop function if exists public.deposit_for_town(integer);
drop table if exists public.deposits;

-- ─── feed_events ─────────────────────────────────────────────────────────
-- Field usage by kind (plan §457-461):
--   tile_placed   — team + color_id required; qty=1
--   case_opened   — tier required; color_id = rolled color; team NULL
--   crafted       — color_id = output color; qty = produced; team NULL
--   sold          — color_id + qty; team NULL
--   shop_bought   — color_id + qty; team NULL
create table if not exists public.feed_events (
  id          bigint generated by default as identity primary key,
  kind        text not null check (kind in ('tile_placed', 'case_opened', 'crafted', 'sold', 'shop_bought')),
  nickname    text not null,
  team        text null check (team is null or team in ('red', 'blue')),
  color_id    text null,
  qty         int null default 1 check (qty is null or qty > 0),
  tier        text null check (tier is null or tier in ('starter', 'quality', 'fine')),
  created_at  timestamptz not null default now()
);

-- Feed-tail polling (Town tab): both `created_at desc` (timestamp ordering
-- for display) and `id desc` (incremental fetch by `id > sinceId`).
create index if not exists feed_events_recent_idx
  on public.feed_events (created_at desc);

create index if not exists feed_events_id_desc_idx
  on public.feed_events (id desc);

-- ─── Self-trim trigger ───────────────────────────────────────────────────
-- Bound storage at 100 rows. Phase-3 implemented this as an inline DELETE
-- inside each RPC; Phase 4 lifts it to a trigger so place_tile,
-- log_feed_event, AND tick_bots all benefit without each repeating the
-- DELETE statement. STATEMENT-level so a tick_bots burst of 2-5 INSERTs
-- doesn't fire 5 trims — one trim per statement is enough.
--
-- The OFFSET-99 subquery returns the id of the 100th-newest row (or NULL
-- if fewer rows exist). DELETE with id < NULL matches zero rows, so the
-- trigger is a no-op while the table is small.
create or replace function public.trim_feed_events()
returns trigger
language plpgsql
as $$
begin
  delete from public.feed_events
    where id < (
      select id from public.feed_events
        order by id desc
        offset 99 limit 1
    );
  return null;
end;
$$;

drop trigger if exists feed_events_trim_after_insert on public.feed_events;
create trigger feed_events_trim_after_insert
  after insert on public.feed_events
  for each statement
  execute function public.trim_feed_events();

-- ─── RLS ─────────────────────────────────────────────────────────────────
-- SELECT for any authenticated user. INSERT via RPC only (place_tile and
-- log_feed_event, both SECURITY DEFINER).

alter table public.feed_events enable row level security;

drop policy if exists feed_events_select_all on public.feed_events;
create policy feed_events_select_all on public.feed_events
  for select using (auth.role() = 'authenticated');
