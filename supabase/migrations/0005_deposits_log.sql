-- Stridekeep MVB · 0005_deposits_log
-- Append a row per deposit so the Town tab can show a live feed via
-- 30-second polling instead of realtime broadcast (= no fan-out at scale).
-- Self-caps to the last 100 rows so storage stays bounded forever.

create table if not exists public.deposits (
  id          bigint generated by default as identity primary key,
  team        text not null check (team in ('red', 'blue')),
  amount      bigint not null check (amount > 0),
  created_at  timestamptz not null default now()
);

create index if not exists deposits_recent_idx on public.deposits (created_at desc);

alter table public.deposits enable row level security;

drop policy if exists deposits_select_all on public.deposits;
create policy deposits_select_all on public.deposits
  for select to authenticated using (true);

-- Re-create deposit_for_town to also append a row to deposits and trim the
-- table back to its 100-row cap. CREATE OR REPLACE preserves the existing
-- EXECUTE grant from 0003.
create or replace function public.deposit_for_town(p_amount bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_team  text;
  v_total bigint;
begin
  if v_uid is null then
    raise exception 'not authenticated';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'amount must be positive';
  end if;

  if p_amount > 1000000000 then
    raise exception 'amount too large';
  end if;

  select team into v_team from public.users where id = v_uid;
  if v_team is null then
    raise exception 'no team for user';
  end if;

  update public.teams
    set total      = total + p_amount,
        updated_at = now()
    where color = v_team
    returning total into v_total;

  insert into public.deposits (team, amount) values (v_team, p_amount);

  -- Cap the table at 100 rows. Indexed sub-select on id keeps the
  -- delete cheap regardless of how many historical rows existed.
  delete from public.deposits
    where id not in (select id from public.deposits order by id desc limit 100);

  return v_total;
end;
$$;
